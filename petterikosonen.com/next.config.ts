import type { NextConfig } from "next";
import { readFile } from "node:fs/promises";
import { join } from "node:path";

const CSP_ROUTES = [
  "/",
  "/about",
  "/blog",
  "/projects",
  "/research",
  "/contact",
  "/kuu",
  "/labs",
  "/labs/llm",
  "/labs/security",
] as const;

type CspRouteHashes = {
  scriptHashes?: string[];
  styleHashes?: string[];
};

type CspFile = {
  routes?: Record<string, CspRouteHashes>;
};

async function loadCspRoutes(): Promise<Record<string, CspRouteHashes>> {
  try {
    const raw = await readFile(join(process.cwd(), "next.config.csp.json"), "utf8");
    const parsed = JSON.parse(raw) as CspFile;
    return parsed.routes ?? {};
  } catch {
    return {};
  }
}

function buildCsp(route: CspRouteHashes | undefined): string {
  const scriptHashes = route?.scriptHashes ?? [];
  const styleHashes = route?.styleHashes ?? [];
  const scriptSrc = ["'self'", "'wasm-unsafe-eval'", ...scriptHashes].join(" ");
  // Styles: hashes + unsafe-hashes + unsafe-inline (low-risk). Scripts stay hash-strict.
  const styleSrc = ["'self'", "'unsafe-hashes'", "'unsafe-inline'", ...styleHashes].join(" ");
  return [
    "default-src 'self'",
    `script-src ${scriptSrc}`,
    `style-src ${styleSrc}`,
    "img-src 'self' data: blob:",
    "connect-src 'self'",
    "worker-src 'self' blob:",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    "upgrade-insecure-requests",
  ].join("; ");
}

const nextConfig: NextConfig = {
  async headers() {
    const routes = await loadCspRoutes();
    // Hashes generated by scripts/extract-csp-hashes.mjs after build, then
    // patched into routes-manifest.json (turbopack flight hashes change every compile).
    const securityHeaders = [
      { key: "X-Frame-Options", value: "DENY" },
      { key: "X-Content-Type-Options", value: "nosniff" },
      { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
      { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
      { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
      { key: "Cross-Origin-Resource-Policy", value: "same-site" },
      { key: "X-DNS-Prefetch-Control", value: "off" },
      { key: "X-Permitted-Cross-Domain-Policies", value: "none" },
      { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
    ];

    const cspHeaders = CSP_ROUTES.map((source) => ({
      source,
      headers: [{ key: "Content-Security-Policy", value: buildCsp(routes[source]) }],
    }));

    return [
      {
        source: "/wasm/:path*.wasm",
        headers: [{ key: "Content-Type", value: "application/wasm" }],
      },
      {
        source: "/(.*)",
        headers: securityHeaders,
      },
      ...cspHeaders,
    ];
  },
};

export default nextConfig;
