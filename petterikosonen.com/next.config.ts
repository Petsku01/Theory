import type { NextConfig } from "next";
import { readFile } from "node:fs/promises";
import { join } from "node:path";

type CspHashes = {
  scriptHashes?: string[];
  styleHashes?: string[];
};

async function loadCspHashes(): Promise<CspHashes> {
  try {
    const raw = await readFile(join(process.cwd(), "next.config.csp.json"), "utf8");
    return JSON.parse(raw) as CspHashes;
  } catch {
    return { scriptHashes: [], styleHashes: [] };
  }
}

const nextConfig: NextConfig = {
  async headers() {
    const { scriptHashes = [], styleHashes = [] } = await loadCspHashes();
    // Hashes generated by scripts/extract-csp-hashes.mjs after build.
    // No 'unsafe-inline' on script-src (XSS). wasm-unsafe-eval kept for wasm_cortex.
    const scriptSrc = ["'self'", "'wasm-unsafe-eval'", ...scriptHashes].join(" ");
    // 'unsafe-hashes' lets the extracted style="" hashes apply to attributes
    // without restoring 'unsafe-inline' (needed for React inline styles).
    const styleSrc = ["'self'", "'unsafe-hashes'", ...styleHashes].join(" ");
    const csp = [
      "default-src 'self'",
      `script-src ${scriptSrc}`,
      `style-src ${styleSrc}`,
      "img-src 'self' data: blob:",
      "font-src 'self'",
      "connect-src 'self'",
      "worker-src 'self' blob:",
      "frame-src 'self'",
      "object-src 'none'",
      "base-uri 'self'",
      "form-action 'self'",
      "frame-ancestors 'none'",
      "upgrade-insecure-requests",
    ].join("; ");

    return [
      {
        source: "/wasm/:path*.wasm",
        headers: [
          { key: "Content-Type", value: "application/wasm" },
        ],
      },
      {
        source: "/(.*)",
        headers: [
          { key: "X-Frame-Options", value: "DENY" },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
          { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
          { key: "Cross-Origin-Resource-Policy", value: "same-site" },
          { key: "X-DNS-Prefetch-Control", value: "off" },
          { key: "X-Permitted-Cross-Domain-Policies", value: "none" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
          { key: "Content-Security-Policy", value: csp },
        ],
      },
    ];
  },
};

export default nextConfig;
